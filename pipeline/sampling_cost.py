def clusters(n):
    k = math.ceil(n / CLUSTER_MAX)
    return max(ZONES, k) if ZONES else k


def launch_counts(n):
    k = clusters(n)
    return {key: k * LAUNCH_LEAD[key] + (n - k) * LAUNCH_FOLLOW[key] for key in LAUNCH_LEAD}


def monthly_counts(n, interval):
    """Число проб в месяц в установившемся режиме без внеплановых (lambda не определена)."""
    k = clusters(n)
    full = k * FULL_PER_CLUSTER_PER_YEAR / 12
    return {
        "water": n / interval + n / P3_INTERVAL_MONTHS + full,
        "smear": n / interval,
        "chem": k / CHEM_SHORT_INTERVAL_MONTHS + full,
        "metals": full,
    }


def ref_cost(c, lab_sampling=False):
    """Стоимость по ориентиру Шабац, RSD без налога, только для типов с ценой. Возвращает (сумма, список без цены)."""
    total = (c["water"] * REF_PRICE["micro_water"] + c["chem"] * REF_PRICE["chem_k"]
             + c["metals"] * REF_PRICE["metals_pack"])
    if lab_sampling:
        total += c["water"] * REF_PRICE["lab_sampling_micro"] + (c["chem"] + c["metals"]) * REF_PRICE["lab_sampling_chem"]
    return total


