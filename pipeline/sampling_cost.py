#  остальные точки кластера: этап 1 = P3 (вода) + P4 (вода, смыв) ; химия-К P4 ; этап 2 как у ведущей
LAUNCH_LEAD = {"water": 3 + 2, "smear": 1 + 2, "chem": 3, "metals": 2}
LAUNCH_FOLLOW = {"water": 2 + 2, "smear": 1 + 2, "chem": 1, "metals": 0}

