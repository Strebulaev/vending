def listing_calc(lst):
    w, d, h = lst["pack_cm"]
    cbm = w * d * h / 1e6
    kg = lst["gross_kg"]
    chargeable_air = max(kg, w * d * h / VOL_DIV_AIR)
    chargeable_exp = max(kg, w * d * h / VOL_DIV_EXPRESS)
    return cbm, chargeable_air, chargeable_exp


